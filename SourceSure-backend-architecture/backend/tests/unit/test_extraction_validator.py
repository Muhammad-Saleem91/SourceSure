# ─── Conflict detection ───────────────────────────────────────────────────────

def test_no_conflict_if_same_value():
    prior = ValidatedClaim(
        field_key="lead_time_days", raw_value="24 days", normalized_value=24.0,
        unit="day", state=STATE_SUPPORTED, confidence=0.95,
        quoted_text="Lead time 24 days.", page_number=1,
        sheet_name=None, cell_range=None, section=None,
    )
    claim = make_claim(normalized_value=24, field_key="lead_time_days")
    report = run(make_output(claim), existing=[prior])
    assert report.validated[0].state == STATE_SUPPORTED
    assert report.has_conflicts is False


def test_conflict_detected_different_value():
    prior = ValidatedClaim(
        field_key="lead_time_days", raw_value="24 days", normalized_value=24.0,
        unit="day", state=STATE_SUPPORTED, confidence=0.95,
        quoted_text="Lead time 24 days.", page_number=1,
        sheet_name=None, cell_range=None, section=None,
    )
    claim = make_claim(normalized_value=35, field_key="lead_time_days")
    report = run(make_output(claim), existing=[prior])
    assert report.validated[0].state == STATE_CONFLICTING
    assert prior.state == STATE_CONFLICTING  # retroactive marking
    assert report.has_conflicts is True


def test_low_confidence_does_not_trigger_conflict():
    prior = ValidatedClaim(
        field_key="lead_time_days", raw_value="24 days", normalized_value=24.0,
        unit="day", state=STATE_SUPPORTED, confidence=0.95,
        quoted_text="Lead time 24 days.", page_number=1,
        sheet_name=None, cell_range=None, section=None,
    )
    # Low confidence claim with different value → should NOT mark prior as CONFLICTING
    claim = make_claim(normalized_value=99, confidence=0.3, field_key="lead_time_days")
    report = run(make_output(claim), existing=[prior])
    assert report.validated[0].state == STATE_LOW_CONFIDENCE
    assert prior.state == STATE_SUPPORTED  # must NOT be marked CONFLICTING


