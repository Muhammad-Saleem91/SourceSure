"""
Unit tests for ai/extraction_validator.py — Module 2.3b

All tests use synthetic ExtractedClaim objects — no Gemini API key required.
The validator is a pure function so every case is deterministic.
"""

import pytest
from app.ai.extraction_schema import ExtractedClaim, ExtractionOutput
from app.ai.extraction_validator import (
    STATE_CONFLICTING,
    STATE_LOW_CONFIDENCE,
    STATE_SUPPORTED,
    ValidatedClaim,
    validate_and_normalize,
)
from app.parsers.base import ParsedChunk

# ─── Helpers ─────────────────────────────────────────────────────────────────

VALID_KEYS = {"lead_time_days", "capacity_monthly", "iso_9001", "country", "cert_expiry"}


def make_claim(**kwargs) -> ExtractedClaim:
    # Removed page_number, sheet_name, cell_range, section as they are no longer generated by the LLM
    defaults = dict(
        field_key="lead_time_days",
        raw_value="24 days",
        normalized_value=24,
        unit="day",
        confidence=0.95,
        quoted_text="Lead time is 24 days from order confirmation."
    )
    return ExtractedClaim(**{**defaults, **kwargs})


def make_output(*claims: ExtractedClaim) -> ExtractionOutput:
    return ExtractionOutput(claims=list(claims))


def run(output, existing=None):
    # Mock chunks so that quoted text passes deterministic validation
    chunks = []
    for claim in output.claims:
        if claim.quoted_text and claim.quoted_text.strip():
            chunks.append(ParsedChunk(
                text=f"Prefix text {claim.quoted_text} Suffix text",
                section=None,
                page_number=1,
                sheet_name=None,
                cell_range=None
            ))
    return validate_and_normalize(output, VALID_KEYS, parsed_chunks=chunks, existing_claims=existing)


# ─── Gate 1: field_key validation ────────────────────────────────────────────

def test_unknown_field_key_is_rejected():
    claim = make_claim(field_key="unknown_field_xyz")
    report = run(make_output(claim))
    assert len(report.validated) == 0
    assert report.rejected_count == 1
    assert "unknown_field_xyz" in report.rejection_reasons[0]


def test_known_field_key_passes():
    claim = make_claim(field_key="lead_time_days")
    report = run(make_output(claim))
    assert len(report.validated) == 1


# ─── Gate 2: quoted_text validation ──────────────────────────────────────────

def test_empty_quoted_text_is_rejected():
    claim = make_claim(quoted_text="")
    report = run(make_output(claim))
    assert report.rejected_count == 1


def test_whitespace_quoted_text_is_rejected():
    claim = make_claim(quoted_text="   ")
    report = run(make_output(claim))
    assert report.rejected_count == 1


