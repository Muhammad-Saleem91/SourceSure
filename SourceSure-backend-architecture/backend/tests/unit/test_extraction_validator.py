# ─── Deterministic Provenance Pipeline Tests ──────────────────────────────────

def test_validator_pdf_unique_quote():
    chunks = [
        ParsedChunk(text="ISO 9001 Certification, Not Certified, Supplier C does not hold this.", page_number=1, sheet_name=None, cell_range=None, section=None),
        ParsedChunk(text="Other text on page 2.", page_number=2, sheet_name=None, cell_range=None, section=None)
    ]
    claim = make_claim(field_key="iso_9001", raw_value="Not Certified", normalized_value=False, quoted_text="Supplier C does not hold this.")
    report = validate_and_normalize(make_output(claim), VALID_KEYS, chunks)
    
    assert len(report.validated) == 1
    val_claim = report.validated[0]
    assert val_claim.state == "SUPPORTED"
    assert val_claim.page_number == 1
    assert val_claim.sheet_name is None
    assert val_claim.provenance_method == "DETERMINISTIC_QUOTE_MATCH"
    assert val_claim.validation_reason == "UNIQUE_SOURCE_MATCH"

