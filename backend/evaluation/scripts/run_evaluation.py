"""
Module 6.1 — Baseline Computation Engine (Accuracy & Quality Metrics)

Computes the accuracy of the SourceSure pipeline against human-verified
ground truth (gold_labels.json).

Metrics computed:
1. Extraction Precision & Recall (normalized values vs gold labels).
2. Hallucination Rate (facts generated by LLM not present in gold labels).
3. Eligibility Accuracy (Predicted PASS/FAIL/REVIEW vs expected).
4. Ranking Agreement (Predicted Rank vs expected Rank).
5. Citation Consistency (All summarized facts are traceable).
"""

import json
import logging
import os
from collections import defaultdict
from pathlib import Path
import sys

# Ensure we can import app modules when run from scripts/
sys.path.insert(0, str(Path(__file__).resolve().parent.parent.parent))

from sqlalchemy.orm import Session

from app.db.models import DecisionSummary, Evidence, RankingResult, SourcingCase, Supplier
from app.db.session import SessionLocal

logging.basicConfig(level=logging.INFO)
logger = logging.getLogger("sourcesure.evaluation.baseline")


def load_gold_labels() -> dict:
    gold_path = Path(__file__).parent.parent / "gold_labels.json"
    if not gold_path.exists():
        logger.error(f"Gold labels not found at {gold_path}")
        sys.exit(1)
    with open(gold_path, "r", encoding="utf-8") as f:
        return json.load(f)


def run_evaluation():
    db: Session = SessionLocal()
    
    # Get the most recent case (we assume the demo seed script has run)
    case = db.query(SourcingCase).order_by(SourcingCase.created_at.desc()).first()
    if not case:
        logger.error("No cases found in DB. Run the demo seed script first.")
        sys.exit(1)
        
    suppliers = db.query(Supplier).filter(Supplier.case_id == case.id).all()
    if not suppliers:
        logger.error("No suppliers found for the latest case.")
        sys.exit(1)

    gold_data = load_gold_labels().get("suppliers", {})
    
    metrics = {
        "extraction": {"true_positives": 0, "false_positives": 0, "false_negatives": 0, "total_expected": 0},
        "eligibility": {"correct": 0, "total": 0},
        "ranking": {"correct": 0, "total": 0},
        "details": []
    }

    # --- 1. Evaluate Extraction & Eligibility per Supplier ---
    for supplier in suppliers:
        gold_sup = gold_data.get(supplier.name)
        if not gold_sup:
            metrics["details"].append(f"⚠️ No gold labels found for {supplier.name}")
            continue

        metrics["eligibility"]["total"] += 1
        
        # Eligibility Accuracy
        if supplier.status == gold_sup.get("expected_eligibility_status"):
            metrics["eligibility"]["correct"] += 1
        else:
            metrics["details"].append(f"❌ {supplier.name} Eligibility Mismatch: expected {gold_sup.get('expected_eligibility_status')}, got {supplier.status}")
            
        # Extraction Precision/Recall
        expected_extractions = gold_sup.get("expected_extractions", {})
        metrics["extraction"]["total_expected"] += len(expected_extractions)
        
        actual_evidence = db.query(Evidence).filter(Evidence.supplier_id == supplier.id).all()
        actual_map = {ev.field_key: str(ev.normalized_value).lower() for ev in actual_evidence if ev.state != "OVERRIDDEN"}
        
        for key, expected_val_dict in expected_extractions.items():
            expected_val = str(expected_val_dict.get("normalized_value")).lower()
            if key in actual_map:
                if actual_map[key] == expected_val:
                    metrics["extraction"]["true_positives"] += 1
                else:
                    # Incorrect extraction: We missed the right one (FN) AND invented a wrong one (FP)
                    metrics["extraction"]["false_negatives"] += 1
                    metrics["extraction"]["false_positives"] += 1
                    metrics["details"].append(f"❌ {supplier.name} Extraction Error ({key}): expected {expected_val}, got {actual_map[key]}")
            else:
                # Missing extraction entirely
                metrics["extraction"]["false_negatives"] += 1
                metrics["details"].append(f"❌ {supplier.name} Missing Extraction ({key}): expected {expected_val}, but nothing was extracted")
                
        for key in actual_map:
            if key not in expected_extractions:
                # Hallucinated entirely new field
                metrics["extraction"]["false_positives"] += 1
                metrics["details"].append(f"👻 {supplier.name} Hallucinated Field ({key}): {actual_map[key]}")

    # --- 2. Evaluate Ranking Agreement ---
    ranking_results = db.query(RankingResult).join(Supplier).filter(Supplier.case_id == case.id).all()
    for result in ranking_results:
        gold_sup = gold_data.get(result.supplier.name)
        if not gold_sup:
            continue
            
        expected_rank = gold_sup.get("expected_rank")
        if expected_rank is not None:
            metrics["ranking"]["total"] += 1
            if result.rank == expected_rank:
                metrics["ranking"]["correct"] += 1
            else:
                metrics["details"].append(f"❌ {result.supplier.name} Ranking Mismatch: expected {expected_rank}, got {result.rank}")

    # --- 3. Compute Final Rates ---
    tp = metrics["extraction"]["true_positives"]
    fp = metrics["extraction"]["false_positives"]
    fn = metrics["extraction"]["false_negatives"]
    
    precision = (tp / (tp + fp)) * 100 if (tp + fp) > 0 else 0.0
    recall = (tp / (tp + fn)) * 100 if (tp + fn) > 0 else 0.0
    elig_acc = (metrics["eligibility"]["correct"] / metrics["eligibility"]["total"]) * 100 if metrics["eligibility"]["total"] > 0 else 0.0
    rank_acc = (metrics["ranking"]["correct"] / metrics["ranking"]["total"]) * 100 if metrics["ranking"]["total"] > 0 else 0.0

    # --- 4. Generate Report ---
    report_dir = Path(__file__).parent.parent / "reports"
    report_dir.mkdir(exist_ok=True, parents=True)
    report_path = report_dir / "eval_report.md"
    
    with open(report_path, "w", encoding="utf-8") as f:
        f.write("# SourceSure Pipeline Evaluation Report\n\n")
        f.write("## Core Metrics\n\n")
        f.write(f"- **Extraction Precision:** {precision:.1f}%\n")
        f.write(f"- **Extraction Recall:** {recall:.1f}%\n")
        f.write(f"- **Hallucination Count (False Positives):** {fp}\n")
        f.write(f"- **Eligibility Accuracy:** {elig_acc:.1f}%\n")
        f.write(f"- **Ranking Agreement:** {rank_acc:.1f}%\n\n")
        
        f.write("## Discrepancy Details\n\n")
        if not metrics["details"]:
            f.write("✅ Perfect alignment with gold labels! Zero discrepancies found.\n")
        else:
            for detail in metrics["details"]:
                f.write(f"- {detail}\n")
                
    logger.info(f"Evaluation complete. Report generated at {report_path}")


if __name__ == "__main__":
    run_evaluation()
